"""Week 4 (4.4): what each component contributes. Runs the agent on the dev split once per configuration, each with one
component switched off (or the reranker switched on), and writes the ablation table.

    python -m scripts.ablations --list                      # configurations and what they change
    python -m scripts.ablations                             # all of them (dev only, D12); LLM_CACHE=1 recommended
    python -m scripts.ablations --configs agent,no_critic   # a subset; earlier rows in the report are kept
    LLM_BACKEND=mock python -m scripts.ablations            # offline pipeline check (numbers meaningless)

Rows also shown for reference: the best Week 1 single prompt (dev, docs/baselines.md) and, if reports/agent_eval_v1.json
holds a dev run, the Week 3 agent before the D40 fixes. Dev only: test was run once at the Week 3 gate and is not used to
measure changes. One run per configuration: on 30 queries one query is 3.3 points, so a difference of one query is noise
(the 4.1 benchmark measures run-to-run variance).
Writes reports/ablations_v1.json and docs/ablations.md (Team notes kept).
"""
from __future__ import annotations

import argparse
import json
import os
import time

from dotenv import load_dotenv

from app import llm_client
from app.retrieval.chunking import ROOT
from scripts.agent_eval import WEEK1_DEV, evaluate, load_eval, run_one, warm_up

load_dotenv()
REPORT = ROOT / "reports" / "ablations_v1.json"
DOC = ROOT / "docs" / "ablations.md"
CONFIGS: dict[str, tuple[str, dict]] = {
    "agent": ("Full agent (Week 4, with the D40 fixes)", {}),
    "no_key_facts": ("Without key facts first (D40 fix 1)", {"AGENT_KEY_FACTS": "0"}),
    "no_citation_enum": ("Without citations limited to real ids (D40 fix 2)", {"AGENT_CITATION_ENUM": "0"}),
    "no_critic": ("Without the code critic and its replan (D34)", {"AGENT_CRITIC": "0"}),
    "no_json_retry": ("Without JSON repair and retry (D32)", {"AGENT_JSON_RETRY": "0"}),
    "no_constrained": ("Without constrained decoding: JSON mode only (D32)", {"LLM_CONSTRAINED": ""}),
    "multi_agent": ("Multi-agent architecture: supervisor, 3 specialists, verifier (D44)", {"AGENT_ARCH": "multi"}),
    "with_reranker": ("With the MiniLM reranker on the top 12 (D38)", {"RERANK_BACKEND": "cross_encoder", "RERANK_MODEL": "minilm",
                                                                       "RERANK_CANDIDATES": "12"}),
}
COLS = [("accuracy", "Accuracy", "{:.3f}"), ("task_completion_rate", "Completion", "{:.0%}"),
        ("fact_recall", "Fact recall", "{:.2f}"), ("citation_hit_rate", "Citation hit", "{:.2f}"),
        ("citation_precision", "Citation precision", "{:.2f}"), ("injection_resistance", "Injection reported", "{:.2f}"),
        ("json_first_try_rate", "JSON first try", "{:.0%}"), ("avg_tool_calls_per_task", "Tool calls", "{:.2f}"),
        ("tokens_median", "Tokens (median)", "{:,}"), ("latency_p50_ms", "p50", "{}"), ("latency_p95_ms", "p95", "{}")]


def run_config(name: str, qs: list[dict]) -> dict:
    label, env = CONFIGS[name]
    saved = {k: os.environ.get(k) for k in env}
    os.environ.update(env)
    try:
        from app.retrieval import service
        service.reset()                                       # the reranker setting is part of the retrieval pipeline
        warm_up()
        runs = []
        for i, q in enumerate(qs, 1):
            r = run_one(q)
            o = r.get("output") or {}
            print(f"  [{name} {i}/{len(qs)}] {q['id']} -> {o.get('behaviour', 'CRASH')} steps={r['steps']} tokens={r['tokens']}",
                  flush=True)
            runs.append(r)
        res = evaluate(qs, runs, f"dev · {name}")
        res["label"], res["env"], res["run_at"] = label, env, time.strftime("%Y-%m-%d %H:%M")
        return res
    finally:
        for k, v in saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v


def fmt(key: str, val, spec: str) -> str:
    if val is None:
        return "–"
    if key.startswith("latency"):
        return f"{val / 1000:.1f} s"
    try:
        return spec.format(val)
    except (ValueError, TypeError):
        return str(val)


def write_markdown(report: dict):
    base = (report["configs"].get("agent") or {}).get("metrics", {}).get("accuracy")
    L = ["# Ablations (Week 4, step 4.4)", "",
         f"Model `{report['model']}` · dev split ({report.get('queries', '?')} queries), one run per configuration · generated by "
         "`python -m scripts.ablations`. Each row switches one component off (or the reranker on) and keeps everything else as "
         "in the full agent. One query is 3.3 points on dev: a difference of one query is noise.", "",
         "| Configuration | Δ accuracy vs full agent | " + " | ".join(c[1] for c in COLS) + " |",
         "|---|---|" + "---|" * len(COLS)]
    w1 = report.get("week1") or {}
    if w1:
        L.append("| Week 1 single prompt, best value per column across its 3 strategies (reference) | "
                 + (f"{w1['accuracy'] - base:+.3f}" if base is not None else "–") + " | "
                 + " | ".join(fmt(k, w1.get(k), s) for k, _, s in COLS) + " |")
    w3 = report.get("week3") or {}
    if w3:
        L.append("| Week 3 agent, before D40 (reference, earlier run) | "
                 + (f"{w3['accuracy'] - base:+.3f}" if base is not None and w3.get("accuracy") is not None else "–") + " | "
                 + " | ".join(fmt(k, w3.get(k), s) for k, _, s in COLS) + " |")
    for name in CONFIGS:
        res = report["configs"].get(name)
        if not res:
            continue
        m = res["metrics"]
        delta = "baseline" if name == "agent" else (f"{m['accuracy'] - base:+.3f}" if base is not None else "–")
        L.append(f"| {res['label']} | {delta} | " + " | ".join(fmt(k, m.get(k), s) for k, _, s in COLS) + " |")
    L += ["", "Failure classes per configuration (primary class per failed query):", "",
          "| Configuration | Tool-call error | Retrieval miss | Hallucination | Reasoning error |", "|---|---|---|---|---|"]
    for name in CONFIGS:
        res = report["configs"].get(name)
        if res:
            t = res["metrics"]["failure_taxonomy"]
            L.append(f"| {res['label']} | {t['tool-call error']} | {t['retrieval miss']} | {t['hallucination']} | {t['reasoning error']} |")
    L += ["", "## Reading the table", "",
          "- The component matters if switching it off lowers accuracy by more than one or two queries, or moves failures "
          "into its class (no critic → hallucination, no JSON retry or no constrained decoding → tool-call error).",
          "- Band, score, checklist and approvers come from the tools in every configuration, so full reviews mostly pass "
          "whatever is switched off; the differences show on questions.", "", "## Team notes", "",
          "*(M3/M2: add the reading of the results here; the generator keeps everything below this heading.)*", ""]
    old = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
    text = "\n".join(L)
    if "## Team notes" in old:
        text = text[:text.index("## Team notes")] + old[old.index("## Team notes"):]
    DOC.write_text(text, encoding="utf-8", newline="\n")


def week3_reference() -> dict | None:
    p = ROOT / "reports" / "agent_eval_v1.json"
    try:
        dev = json.loads(p.read_text(encoding="utf-8"))["splits"]["dev"]["metrics"]
        return {k: dev.get(k) for k, _, _ in COLS}
    except (OSError, ValueError, KeyError):
        return None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--configs", default=",".join(CONFIGS))
    ap.add_argument("--limit", type=int, default=0, help="first N dev queries only (a quick check, not for the report)")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args(argv)
    if a.list:
        for k, (label, env) in CONFIGS.items():
            print(f"{k:18s} {label}  {env or ''}")
        return
    names = [c.strip() for c in a.configs.split(",") if c.strip()]
    bad = [n for n in names if n not in CONFIGS]
    if bad:
        raise SystemExit(f"unknown configuration(s): {', '.join(bad)}; see --list")
    qs = [q for q in load_eval() if q["split"] == "dev"][: a.limit or None]
    mock = llm_client.backend() == "mock"
    print(f"{len(names)} configuration(s) x {len(qs)} dev queries. Rough cost with an empty cache: up to ~150k tokens per "
          f"configuration; calls shared with an earlier configuration come from the cache when LLM_CACHE=1 "
          f"(now {os.getenv('LLM_CACHE', '0')}).", flush=True)
    report_path = REPORT if not (mock or a.limit) else ROOT / "reports" / ("mock" if mock else "smoke") / "ablations.json"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report = {"model": "mock" if mock else os.getenv("LLM_MODEL", "?"), "queries": len(qs), "configs": {}}
    if report_path.exists():
        try:
            old = json.loads(report_path.read_text(encoding="utf-8"))
            if old.get("model") == report["model"] and old.get("queries") == len(qs):
                report["configs"] = old.get("configs", {})
        except ValueError:
            pass
    report["week1"] = {"accuracy": max(WEEK1_DEV["accuracy"]), "fact_recall": max(WEEK1_DEV["fact_recall"]),
                       "injection_resistance": max(WEEK1_DEV["injection_resistance"]),
                       "tokens_median": min(WEEK1_DEV["tokens_per_query"])}
    report["week3"] = week3_reference()
    for n in names:
        print(f"\n== {n}: {CONFIGS[n][0]}", flush=True)
        report["configs"][n] = run_config(n, qs)
        m = report["configs"][n]["metrics"]
        print(f"   accuracy {m['accuracy']} | completion {m['task_completion_rate']} | taxonomy {m['failure_taxonomy']} | "
              f"BM25 fallbacks {m.get('dense_fallbacks', 0)}, tool retries {m.get('tool_retries', 0)}", flush=True)
        report_path.write_text(json.dumps(report, indent=1, default=str), encoding="utf-8", newline="\n")   # after each config
    if report_path == REPORT:
        write_markdown(report)
        print(f"\nwrote {REPORT.relative_to(ROOT)} and {DOC.relative_to(ROOT)}")
    else:
        print(f"\nwrote {report_path.relative_to(ROOT)} (check run; docs/ablations.md is written by full dev runs only)")


if __name__ == "__main__":
    main()
